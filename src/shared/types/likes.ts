/**
 * 点赞接口配置：对接自建后端（`/api/v1/posts/{slug}/likes`）。
 *
 * 和评论、访问统计指向同一台服务，但单独一份配置：关掉访问统计不该连带把点赞
 * 关掉，三者的开关语义各管各的。
 */
export type LikeApiConfig = {
	/**
	 * 是否启用服务端点赞。
	 *
	 * 关掉之后按钮只显示数据源里的基数、点击不写任何东西 —— 不会假装点上了。
	 * 早期版本把点赞存在 localStorage，那是「换设备就丢、别人看不见」的假象，
	 * 所以这里没有退回本地的分支。
	 */
	enable: boolean;
	/** 后端 API 基地址，末尾不要带斜杠；部署后改成公网地址 */
	apiBaseUrl: string;
	/** 请求超时（毫秒）。失败时按钮回滚到点击前的样子，不阻塞页面 */
	requestTimeoutMs: number;
};
