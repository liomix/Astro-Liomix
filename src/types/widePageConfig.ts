/**
 * 宽幅页面（「大页」）布局
 * ---------------------------------------------------------------------------
 * 有些页面天生需要横向空间（留言墙、相册大图流之类），侧栏和 17.5rem 的列
 * 只会把正文挤窄。打开这个开关后，命中的页面会：
 *   1. 隐藏左右侧栏列与多标签导航栏 —— 列几何改成单列，正文真的变宽（不是藏卡片）；
 *   2. 面板宽度从 92vw 放开到 96vw（移动端本来就是铺满，不受影响）。
 *
 * 这是「页面级」状态，和导航页纯净模式一样在 swup 切页时按目标 URL 同步：
 * 面板与侧栏都在容器之外、只 SSR 一次，只写首屏的话软导航后会留在上一页的形态。
 */
export type WidePageConfig = {
	/** 总开关 */
	enable: boolean;
	/** 需要宽幅布局的页面路径（前缀命中，与纯净模式的路径判定同一套） */
	paths: string[];
};
