import rss, { type RSSFeedItem } from "@astrojs/rss";
import type { APIContext } from "astro";
import { siteConfig } from "@/shared/config/siteConfig";
import { getSortedPosts } from "@/shared/lib/content/content-utils";
import { renderFeedEntries } from "@/shared/lib/content/feed-utils";
import { formatDateI18nWithTime } from "@/shared/lib/format/date";
import pkg from "../../package.json";

export const prerender = true;

export async function GET(context: APIContext): Promise<Response> {
	const includeContent = (siteConfig.feed?.contentMode ?? "full") === "full";
	const blog = await getSortedPosts();
	const entries = await renderFeedEntries(blog, { includeContent });
	const feedItems: RSSFeedItem[] = entries.map((entry) => ({
		title: entry.title,
		pubDate: entry.published,
		description: entry.description,
		link: entry.link,
		...(includeContent ? { content: entry.content } : {}),
	}));
	return rss({
		title: siteConfig.title,
		description: siteConfig.subtitle || "No description",
		site: context.site ?? "https://firefly.cuteleaf.cn",
		customData: `<templateTheme>Firefly</templateTheme>
		<templateThemeVersion>${pkg.version}</templateThemeVersion>
		<templateThemeUrl>https://github.com/CuteLeaf/Firefly</templateThemeUrl>
		<lastBuildDate>${formatDateI18nWithTime(new Date())}</lastBuildDate>`,
		items: feedItems,
	});
}
